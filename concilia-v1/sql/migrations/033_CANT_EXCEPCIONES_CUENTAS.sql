-- Concilia V1: conservar excepciones CANT sin asignar reglas contables.
-- Aplicar exclusivamente en concilia_test despues de la migracion 032.
CREATE TABLE IF NOT EXISTS public.con_cant_excepcion_cuenta (
    id_excepcion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_archivo BIGINT NOT NULL REFERENCES public.con_archivo_carga(id_archivo),
    id_jornada BIGINT NOT NULL REFERENCES public.con_jornada(id_jornada),
    linea_origen BIGINT NOT NULL CHECK (linea_origen > 0),
    cuenta TEXT NOT NULL,
    correlation_id VARCHAR(64) NOT NULL,
    motivo TEXT NOT NULL DEFAULT 'CUENTA_SIN_REGLA_APROBADA',
    fec_registro TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_cant_excepcion_archivo_linea UNIQUE(id_archivo,linea_origen)
);
CREATE INDEX IF NOT EXISTS ix_cant_excepcion_jornada
    ON public.con_cant_excepcion_cuenta(id_jornada);
