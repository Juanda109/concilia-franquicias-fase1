CREATE TABLE CON_CATALOGO_INSUMO (
    ID_CATALOGO_INSUMO BIGSERIAL PRIMARY KEY,
    TIPO_INSUMO VARCHAR(40) NOT NULL,
    FUENTE VARCHAR(30) NOT NULL,
    VERSION_CATALOGO INTEGER NOT NULL,
    OBLIGATORIO BOOLEAN,
    ACTIVO BOOLEAN NOT NULL DEFAULT TRUE,
    FEC_DESDE DATE NOT NULL,
    FEC_HASTA DATE,

    CONSTRAINT UQ_CATALOGO_INSUMO_VERSION
        UNIQUE (TIPO_INSUMO, VERSION_CATALOGO),

    CONSTRAINT CK_CATALOGO_VIGENCIA
        CHECK (FEC_HASTA IS NULL OR FEC_HASTA >= FEC_DESDE),

    CONSTRAINT CK_CATALOGO_TIPO_F1
        CHECK (TIPO_INSUMO IN (
            'HA22', 'HA26', 'HA32',
            'CAET', 'CANT', 'DEPO',
            'CARTA_COMPENSACION',
            'PMD', 'MEP', 'VSS'
        )),

    CONSTRAINT CK_CATALOGO_FUENTE_F1
        CHECK (
            (FUENTE = 'HOST' AND
             TIPO_INSUMO IN ('HA22','HA26','HA32'))
            OR
            (FUENTE = 'CREDIBANCO' AND
             TIPO_INSUMO IN (
                 'CAET','CANT','DEPO','CARTA_COMPENSACION'))
            OR
            (FUENTE = 'REDEBAN' AND
             TIPO_INSUMO IN ('PMD','MEP'))
            OR
            (FUENTE = 'VISA' AND TIPO_INSUMO = 'VSS')
        )
);

CREATE OR REPLACE FUNCTION FN_INICIALIZAR_INSUMOS_JORNADA(
    P_ID_JORNADA BIGINT,
    P_VERSION_CATALOGO INTEGER
)
RETURNS INTEGER
LANGUAGE plpgsql
AS $$
DECLARE
    V_FECHA DATE;
    V_TOTAL INTEGER;
    V_INSERTADOS INTEGER;
BEGIN
    SELECT FECHA_CONTABLE
      INTO V_FECHA
      FROM CON_JORNADA
     WHERE ID_JORNADA = P_ID_JORNADA
     FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Jornada inexistente: %', P_ID_JORNADA;
    END IF;

    SELECT COUNT(*)
      INTO V_TOTAL
      FROM CON_CATALOGO_INSUMO
     WHERE VERSION_CATALOGO = P_VERSION_CATALOGO
       AND ACTIVO = TRUE
       AND OBLIGATORIO IS NOT NULL
       AND FEC_DESDE <= V_FECHA
       AND (FEC_HASTA IS NULL OR FEC_HASTA >= V_FECHA);

    IF V_TOTAL <> 10 THEN
        RAISE EXCEPTION
          'Catalogo incompleto para jornada %, version %: % de 10',
          P_ID_JORNADA, P_VERSION_CATALOGO, V_TOTAL;
    END IF;

    INSERT INTO CON_INSUMO_ESPERADO (
        ID_JORNADA, TIPO_INSUMO, FUENTE,
        OBLIGATORIO, ESTADO
    )
    SELECT
        P_ID_JORNADA, TIPO_INSUMO, FUENTE,
        OBLIGATORIO, 'PENDIENTE'
    FROM CON_CATALOGO_INSUMO
    WHERE VERSION_CATALOGO = P_VERSION_CATALOGO
      AND ACTIVO = TRUE
      AND OBLIGATORIO IS NOT NULL
      AND FEC_DESDE <= V_FECHA
      AND (FEC_HASTA IS NULL OR FEC_HASTA >= V_FECHA)
    ON CONFLICT (ID_JORNADA, TIPO_INSUMO) DO NOTHING;

    GET DIAGNOSTICS V_INSERTADOS = ROW_COUNT;
    RETURN V_INSERTADOS;
END;
$$;
