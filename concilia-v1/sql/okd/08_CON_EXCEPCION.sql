CREATE TABLE CON_EXCEPCION (
  ID_EXCEPCION BIGSERIAL PRIMARY KEY,
  ID_CRUCE BIGINT NOT NULL REFERENCES CON_CRUCE(ID_CRUCE),
  TIPO_EXCEPCION VARCHAR(50) NOT NULL,
  ESTADO VARCHAR(30) NOT NULL,
  CAUSA VARCHAR(500),
  RESPONSABLE VARCHAR(100),
  FEC_APERTURA TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FEC_CIERRE TIMESTAMP
);
