-- CONCILIA V1 SIN IA - OKD
-- 01 CON_ARCHIVO_CARGA

CREATE TABLE CON_ARCHIVO_CARGA (
  ID_ARCHIVO BIGSERIAL PRIMARY KEY,
  FECHA_CONTABLE DATE NOT NULL,
  PROCESO_ORIGEN VARCHAR(30) NOT NULL,
  TIPO_ARCHIVO VARCHAR(40) NOT NULL,
  FRANQUICIA VARCHAR(30),
  NOMBRE_ARCHIVO VARCHAR(255) NOT NULL,
  RUTA_ARCHIVO VARCHAR(500) NOT NULL,
  CHECKSUM_SHA256 CHAR(64) NOT NULL UNIQUE,
  TOTAL_REGISTROS BIGINT,
  ESTADO VARCHAR(30) NOT NULL,
  CORRELATION_ID VARCHAR(64) NOT NULL,
  FEC_RECEPCION TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);


-- CONCILIA V1 SIN IA - OKD
-- 02 CON_JORNADA

CREATE TABLE CON_JORNADA (
  ID_JORNADA BIGSERIAL PRIMARY KEY,
  FECHA_CONTABLE DATE NOT NULL UNIQUE,
  ESTADO VARCHAR(30) NOT NULL,
  HA22_RECIBIDO BOOLEAN DEFAULT FALSE,
  HA26_RECIBIDO BOOLEAN DEFAULT FALSE,
  HA32_RECIBIDO BOOLEAN DEFAULT FALSE,
  PMRD8000_RECIBIDO BOOLEAN DEFAULT FALSE,
  PMPD1322_RECIBIDO BOOLEAN DEFAULT FALSE,
  TOTAL_ARCHIVOS INTEGER DEFAULT 0,
  FEC_INICIO TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FEC_COMPLETITUD TIMESTAMP
);


-- CONCILIA V1 SIN IA - OKD
-- 03 CON_HOST_RESULTADO

CREATE TABLE CON_HOST_RESULTADO (
  ID_HOST_RESULTADO BIGSERIAL PRIMARY KEY,
  ID_ARCHIVO BIGINT NOT NULL REFERENCES CON_ARCHIVO_CARGA(ID_ARCHIVO),
  FECHA_CONTABLE DATE NOT NULL,
  TX_HOST VARCHAR(10) NOT NULL,
  CUENTA VARCHAR(30) NOT NULL,
  CENTRO VARCHAR(10),
  REFERENCIA VARCHAR(80),
  CONCEPTO VARCHAR(80),
  VALOR_DEBE NUMERIC(20,2),
  VALOR_HABER NUMERIC(20,2),
  VALOR_SALDO NUMERIC(20,2),
  VALOR_NORMALIZADO NUMERIC(20,2) NOT NULL,
  LINEA_ORIGEN BIGINT,
  CORRELATION_ID VARCHAR(64) NOT NULL
);

-- INDICES
CREATE INDEX IX_HOST_FECHA_TX_CTA ON CON_HOST_RESULTADO(FECHA_CONTABLE,TX_HOST,CUENTA);


-- CONCILIA V1 SIN IA - OKD
-- 04 CON_FRANQUICIA_RESULTADO

