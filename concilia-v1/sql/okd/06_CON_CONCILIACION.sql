CREATE TABLE CON_CONCILIACION (
  ID_CONCILIACION BIGSERIAL PRIMARY KEY,
  ID_JORNADA BIGINT NOT NULL REFERENCES CON_JORNADA(ID_JORNADA),
  FECHA_CONTABLE DATE NOT NULL,
  VERSION_REGLAS INTEGER NOT NULL,
  ESTADO VARCHAR(30) NOT NULL,
  TOTAL_CRUCES BIGINT DEFAULT 0,
  TOTAL_CONCILIADOS BIGINT DEFAULT 0,
  TOTAL_DIFERENCIAS BIGINT DEFAULT 0,
  FEC_INICIO TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FEC_FIN TIMESTAMP
);
