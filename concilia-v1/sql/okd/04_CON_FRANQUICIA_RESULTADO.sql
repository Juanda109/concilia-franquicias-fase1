CREATE TABLE CON_FRANQUICIA_RESULTADO (
  ID_FRANQUICIA_RESULTADO BIGSERIAL PRIMARY KEY,
  ID_ARCHIVO BIGINT NOT NULL REFERENCES CON_ARCHIVO_CARGA(ID_ARCHIVO),
  FECHA_CONTABLE DATE NOT NULL,
  PROCESO_ORIGEN VARCHAR(30) NOT NULL,
  REPORTE_ORIGEN VARCHAR(30) NOT NULL,
  FRANQUICIA VARCHAR(30) NOT NULL,
  CUENTA VARCHAR(30),
  CONCEPTO VARCHAR(80),
  REFERENCIA VARCHAR(80),
  MONEDA VARCHAR(5),
  VALOR NUMERIC(20,2),
  LINEA_ORIGEN BIGINT,
  CORRELATION_ID VARCHAR(64) NOT NULL
);

-- INDICES
CREATE INDEX IX_FRANQ_FECHA_CTA ON CON_FRANQUICIA_RESULTADO(FECHA_CONTABLE,FRANQUICIA,CUENTA);
