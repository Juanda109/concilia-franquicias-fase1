CREATE TABLE CON_SALIDA_GENERADA (
  ID_SALIDA BIGSERIAL PRIMARY KEY,
  ID_CONCILIACION BIGINT NOT NULL REFERENCES CON_CONCILIACION(ID_CONCILIACION),
  TIPO_SALIDA VARCHAR(40) NOT NULL,
  NOMBRE_ARCHIVO VARCHAR(255) NOT NULL,
  RUTA_ARCHIVO VARCHAR(500),
  CHECKSUM_SHA256 CHAR(64) NOT NULL,
  TOTAL_REGISTROS BIGINT NOT NULL,
  ESTADO VARCHAR(30) NOT NULL,
  FEC_GENERACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
