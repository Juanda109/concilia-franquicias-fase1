CREATE TABLE CON_CRUCE (
  ID_CRUCE BIGSERIAL PRIMARY KEY,
  ID_CONCILIACION BIGINT NOT NULL REFERENCES CON_CONCILIACION(ID_CONCILIACION),
  FECHA_CONTABLE DATE NOT NULL,
  FRANQUICIA VARCHAR(30),
  CUENTA VARCHAR(30) NOT NULL,
  CONCEPTO VARCHAR(80),
  VALOR_FRANQUICIA NUMERIC(20,2) DEFAULT 0,
  VALOR_HA22 NUMERIC(20,2) DEFAULT 0,
  VALOR_HA26 NUMERIC(20,2) DEFAULT 0,
  VALOR_HA32 NUMERIC(20,2) DEFAULT 0,
  TOTAL_HOST NUMERIC(20,2) DEFAULT 0,
  DIFERENCIA NUMERIC(20,2) DEFAULT 0,
  TX_ESPERADAS VARCHAR(100),
  TX_ENCONTRADAS VARCHAR(100),
  ID_REGLA BIGINT REFERENCES CON_REGLA_CONCILIACION(ID_REGLA),
  VERSION_REGLAS INTEGER,
  MODO_CRUCE VARCHAR(30),
  ESTADO_CONCILIACION VARCHAR(30) NOT NULL,
  OBSERVACION VARCHAR(1000)
);

-- INDICES
CREATE INDEX IX_CRUCE_ESTADO ON CON_CRUCE(ID_CONCILIACION,ESTADO_CONCILIACION);
