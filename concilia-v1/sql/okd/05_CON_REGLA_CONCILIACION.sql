CREATE TABLE CON_REGLA_CONCILIACION (
  ID_REGLA BIGSERIAL PRIMARY KEY,
  CUENTA VARCHAR(30) NOT NULL,
  CONCEPTO VARCHAR(80),
  FRANQUICIA VARCHAR(30),
  TX_ESPERADAS VARCHAR(100) NOT NULL,
  MODO_CRUCE VARCHAR(30) NOT NULL,
  TOLERANCIA NUMERIC(20,2) DEFAULT 0,
  VERSION_REGLA INTEGER NOT NULL,
  ACTIVA BOOLEAN DEFAULT TRUE,
  FEC_DESDE TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FEC_HASTA TIMESTAMP
);
