CREATE TABLE IF NOT EXISTS CON_CANJE_RESULTADO (
  ID_CANJE_RESULTADO BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ID_ARCHIVO BIGINT NOT NULL REFERENCES CON_ARCHIVO_CARGA(ID_ARCHIVO),
  NUMERO_LINEA BIGINT,
  TX VARCHAR(500),
  BIN_DEST VARCHAR(500),
  TIPO VARCHAR(500),
  FECHA_CANJE VARCHAR(500),
  OFI VARCHAR(500),
  TARJETA VARCHAR(500),
  VL_TOTAL NUMERIC(24,4),
  VL_DESCUE NUMERIC(24,4),
  VL_INTERC NUMERIC(24,4),
  PLAZ VARCHAR(500),
  MOT_COB VARCHAR(500),
  IDEN_RED VARCHAR(500),
  COD_ERROR VARCHAR(500),
  MO_TO VARCHAR(500),
  IND_CASH VARCHAR(500),
  ESPACIOS VARCHAR(500),
  COMISION_OP_EXITOSAS NUMERIC(24,4),
  CUENTA VARCHAR(500),
  CUENTAS_COMISIONES NUMERIC(24,4),
  TII_RECIBIDA_EMISOR_VISA_OP_REVER_VENTAS NUMERIC(24,4),
  XX VARCHAR(500),
  CUENTA_880 VARCHAR(500),
  FECHA_CREACION TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS IX_CON_CANJE_RESULTADO_ARCHIVO ON CON_CANJE_RESULTADO(ID_ARCHIVO);
