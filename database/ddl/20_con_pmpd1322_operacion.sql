CREATE TABLE IF NOT EXISTS CON_PMPD1322_OPERACION (
  ID_PMPD1322_OPERACION BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ID_ARCHIVO BIGINT NOT NULL REFERENCES CON_ARCHIVO_CARGA(ID_ARCHIVO),
  ID_INCIDENCIA BIGINT NOT NULL REFERENCES CON_PMPD1322_INCIDENCIA(ID_PMPD1322_INCIDENCIA),
  NUMERO_LINEA BIGINT,
  FECHA_OPERACION DATE,
  IMPORTE NUMERIC(24,4),
  CODIGO_MO VARCHAR(500),
  NUMERO_PAGINA BIGINT,
  FECHA_CREACION TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS IX_CON_PMPD1322_OPERACION_ARCHIVO ON CON_PMPD1322_OPERACION(ID_ARCHIVO);
