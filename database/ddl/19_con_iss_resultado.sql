CREATE TABLE IF NOT EXISTS CON_ISS_RESULTADO (
  ID_ISS_RESULTADO BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ID_ARCHIVO BIGINT NOT NULL REFERENCES CON_ARCHIVO_CARGA(ID_ARCHIVO),
  NUMERO_LINEA BIGINT,
  ENTIDAD_CODIGO VARCHAR(50),
  ENTIDAD_NOMBRE VARCHAR(500),
  FTSRE VARCHAR(50),
  NOMBRE VARCHAR(500),
  MONEDA CHAR(3),
  MONTO_NETO NUMERIC(24,4),
  NATURALEZA CHAR(2),
  FECHA_VALOR DATE,
  FECHA_PROCESAMIENTO DATE,
  FECHA_CREACION TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS IX_CON_ISS_RESULTADO_ARCHIVO ON CON_ISS_RESULTADO(ID_ARCHIVO);
