CREATE TABLE IF NOT EXISTS CON_PMPD1322_INCIDENCIA (
  ID_PMPD1322_INCIDENCIA BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ID_ARCHIVO BIGINT NOT NULL REFERENCES CON_ARCHIVO_CARGA(ID_ARCHIVO),
  NUMERO_LINEA BIGINT,
  OFICINA VARCHAR(500),
  NUMERO VARCHAR(500),
  NUMERO_REFERENCIA VARCHAR(500),
  CODIGO_INCIDENCIA VARCHAR(500),
  RAZON VARCHAR(500),
  NUMERO_TARJETA VARCHAR(500),
  DESCRIPCION VARCHAR(500),
  FECHA_CREACION TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS IX_CON_PMPD1322_INCIDENCIA_ARCHIVO ON CON_PMPD1322_INCIDENCIA(ID_ARCHIVO);
