CREATE TABLE IF NOT EXISTS CON_VSS_DETALLE (
  ID_VSS_DETALLE BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ID_VSS_REPORTE BIGINT NOT NULL REFERENCES CON_VSS_REPORTE(ID_VSS_REPORTE),
  NUMERO_LINEA BIGINT,
  NUMERO_PAGINA BIGINT,
  CLEARING_CURRENCY CHAR(3),
  SECCION VARCHAR(500),
  CONCEPTO VARCHAR(500),
  SUBTIPO VARCHAR(500),
  RATE_TABLE_ID VARCHAR(500),
  COUNT BIGINT,
  CLEARING_AMOUNT NUMERIC(24,4),
  CREDIT_AMOUNT NUMERIC(24,4),
  DEBIT_AMOUNT NUMERIC(24,4),
  TOTAL_AMOUNT NUMERIC(24,4),
  NATURALEZA CHAR(2),
  FECHA_CREACION TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS IX_CON_VSS_DETALLE_REPORTE_PAGINA ON CON_VSS_DETALLE(ID_VSS_REPORTE,NUMERO_PAGINA);
