CREATE TABLE IF NOT EXISTS CON_CONTROL_ARCHIVO (
 ID_CONTROL BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ID_ARCHIVO BIGINT NOT NULL REFERENCES CON_ARCHIVO_CARGA(ID_ARCHIVO), TIPO_CONTROL VARCHAR(80) NOT NULL,
 ESPERADO_REGISTROS BIGINT, OBTENIDO_REGISTROS BIGINT, ESPERADO_VALOR NUMERIC(24,4), OBTENIDO_VALOR NUMERIC(24,4),
 ESTADO VARCHAR(30) NOT NULL, DETALLE JSONB, FECHA_CONTROL TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
