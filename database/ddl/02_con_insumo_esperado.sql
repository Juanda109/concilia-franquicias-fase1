CREATE TABLE IF NOT EXISTS CON_INSUMO_ESPERADO (
 ID_INSUMO BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, FUENTE VARCHAR(30) NOT NULL,
 TIPO_INSUMO VARCHAR(40) NOT NULL UNIQUE, PATRON_ARCHIVO VARCHAR(300), FORMATO VARCHAR(30) NOT NULL,
 OBLIGATORIO BOOLEAN NOT NULL DEFAULT TRUE, ORDEN_VISUAL SMALLINT NOT NULL UNIQUE,
 ESTADO_DESARROLLO VARCHAR(40) NOT NULL, VIGENTE_DESDE DATE, VIGENTE_HASTA DATE, ACTIVO BOOLEAN NOT NULL DEFAULT TRUE
);
