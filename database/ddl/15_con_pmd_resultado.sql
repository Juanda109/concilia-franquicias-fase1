CREATE TABLE IF NOT EXISTS CON_PMD_RESULTADO (
  ID_PMD_RESULTADO BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ID_ARCHIVO BIGINT NOT NULL REFERENCES CON_ARCHIVO_CARGA(ID_ARCHIVO),
  NUMERO_LINEA BIGINT,
  TIPO_TRANSACCION VARCHAR(500),
  NUMERO_TARJETA VARCHAR(500),
  FECHA_COMPROBANTE DATE,
  CODIGO_AUTORIZACION VARCHAR(500),
  NUMERO_COMPROBANTE VARCHAR(500),
  VALOR_PESOS NUMERIC(24,4),
  COMISION_INTERCAMBIO_PESOS NUMERIC(24,4),
  VALOR_DOLARES NUMERIC(24,4),
  COMISION_INTERCAMBIO_DOLARES NUMERIC(24,4),
  CODIGO_ESTABLECIMIENTO VARCHAR(500),
  CODIGO_UNICO VARCHAR(500),
  NOMBRE_ESTABLECIMIENTO VARCHAR(500),
  MOTIVO_CONTRACARGO VARCHAR(500),
  REFERENCIA_CONTRACARGO VARCHAR(500),
  REFERENCIA_UNIVERSAL VARCHAR(500),
  MCC VARCHAR(500),
  CIUDAD VARCHAR(500),
  INDICADOR_DOCUMENTACION VARCHAR(500),
  DE_72_TEXTO VARCHAR(500),
  DATOS_PUNTO_SERVICIO VARCHAR(500),
  IRD VARCHAR(500),
  FECHA_CREACION TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS IX_CON_PMD_RESULTADO_ARCHIVO ON CON_PMD_RESULTADO(ID_ARCHIVO);
