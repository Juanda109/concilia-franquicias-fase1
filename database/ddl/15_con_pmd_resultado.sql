CREATE TABLE IF NOT EXISTS CON_PMD_RESULTADO (
  ID_PMD_RESULTADO BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ID_ARCHIVO BIGINT NOT NULL REFERENCES CON_ARCHIVO_CARGA(ID_ARCHIVO),
  NUMERO_LINEA BIGINT,
  PRODUCTO_SERVICIO VARCHAR(500),
  NIVEL VARCHAR(50),
  DEBITO_CANTIDAD BIGINT,
  DEBITO_VALOR NUMERIC(24,4),
  DEBITO_COMISION_INTERCAMBIO NUMERIC(24,4),
  DEBITO_COMISION_ADMIN NUMERIC(24,4),
  DEBITO_NETO NUMERIC(24,4),
  CREDITO_CANTIDAD BIGINT,
  CREDITO_VALOR NUMERIC(24,4),
  CREDITO_COMISION_INTERCAMBIO NUMERIC(24,4),
  CREDITO_COMISION_ADMIN NUMERIC(24,4),
  CREDITO_NETO NUMERIC(24,4),
  TOTAL NUMERIC(24,4),
  FECHA_CREACION TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS IX_CON_PMD_RESULTADO_ARCHIVO ON CON_PMD_RESULTADO(ID_ARCHIVO);
