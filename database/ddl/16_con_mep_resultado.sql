CREATE TABLE IF NOT EXISTS CON_MEP_RESULTADO (
  ID_MEP_RESULTADO BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ID_ARCHIVO BIGINT NOT NULL REFERENCES CON_ARCHIVO_CARGA(ID_ARCHIVO),
  NUMERO_LINEA BIGINT,
  CENTRO_COSTO VARCHAR(500),
  CUENTA VARCHAR(500),
  DIVISA VARCHAR(500),
  CONTRATO VARCHAR(500),
  REFERENCIA_CRUCE VARCHAR(500),
  IMPORTE NUMERIC(24,4),
  DESCRIPCION VARCHAR(500),
  FECHA DATE,
  TIPO_DOCUMENTO VARCHAR(500),
  NUMERO_DOCUMENTO VARCHAR(500),
  DIGITO_VERIFICACION VARCHAR(500),
  TIPO_PERDIDA VARCHAR(500),
  CLASE_RIESGO VARCHAR(500),
  TIPO_MOVIMIENTO VARCHAR(500),
  PRODUCTO VARCHAR(500),
  PROCESO VARCHAR(500),
  LINEA_OPERATIVA VARCHAR(500),
  VALOR_BASE NUMERIC(24,4),
  FECHA_CREACION TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS IX_CON_MEP_RESULTADO_ARCHIVO ON CON_MEP_RESULTADO(ID_ARCHIVO);
