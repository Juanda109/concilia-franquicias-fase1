CREATE TABLE IF NOT EXISTS CON_PARAMETRO_CLASIFICACION (
 ID_PARAMETRO BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, CODIGO_REGLA VARCHAR(80) NOT NULL,
 TIPO_INSUMO VARCHAR(40) NOT NULL, PRIORIDAD INTEGER NOT NULL, CONDICIONES JSONB NOT NULL, RESULTADO JSONB NOT NULL,
 VERSION INTEGER NOT NULL DEFAULT 1, VIGENTE_DESDE DATE, VIGENTE_HASTA DATE, ACTIVO BOOLEAN NOT NULL DEFAULT TRUE,
 UNIQUE(CODIGO_REGLA,VERSION)
);
