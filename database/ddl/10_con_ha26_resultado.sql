CREATE TABLE IF NOT EXISTS CON_HA26_RESULTADO (
  ID_HA26_RESULTADO BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ID_ARCHIVO BIGINT NOT NULL REFERENCES CON_ARCHIVO_CARGA(ID_ARCHIVO),
  NUMERO_LINEA BIGINT,
  TX_ORIGEN VARCHAR(500),
  TABLA_ORIGEN VARCHAR(500),
  EMPRESA VARCHAR(500),
  NUCTA VARCHAR(500),
  CEORIGEN VARCHAR(500),
  CEDESTIN VARCHAR(500),
  FECON DATE,
  FEPROC DATE,
  NUMAS VARCHAR(500),
  NUMAP VARCHAR(500),
  DEBE NUMERIC(24,4),
  HABER NUMERIC(24,4),
  CLACON VARCHAR(500),
  DESCON VARCHAR(500),
  TIPAPUN VARCHAR(500),
  HAYNUMDO VARCHAR(1),
  NUMDO VARCHAR(500),
  OBSERV VARCHAR(500),
  OBSERV2 VARCHAR(500),
  CODUSU VARCHAR(500),
  HORATR TIMESTAMP(6),
  FECHA_CREACION TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS IX_CON_HA26_RESULTADO_ARCHIVO ON CON_HA26_RESULTADO(ID_ARCHIVO);
