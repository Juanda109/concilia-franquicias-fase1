CREATE TABLE IF NOT EXISTS CON_PMRD8000_RESULTADO (
  ID_PMRD8000_RESULTADO BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ID_ARCHIVO BIGINT NOT NULL REFERENCES CON_ARCHIVO_CARGA(ID_ARCHIVO),
  NUMERO_LINEA BIGINT,
  SECCION VARCHAR(500),
  DETALLE VARCHAR(500),
  NUMERO_REGISTROS BIGINT,
  VALOR_OPERACIONES NUMERIC(24,4),
  VALOR_PROPINAS NUMERIC(24,4),
  VALOR_IVA NUMERIC(24,4),
  VALOR_TOTAL NUMERIC(24,4),
  VALOR_DESCUENTO NUMERIC(24,4),
  VALOR_INTERCAMBIO NUMERIC(24,4),
  FECHA_CREACION TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS IX_CON_PMRD8000_RESULTADO_ARCHIVO ON CON_PMRD8000_RESULTADO(ID_ARCHIVO);
