CREATE TABLE IF NOT EXISTS CON_HA32_RESULTADO (
  ID_HA32_RESULTADO BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ID_ARCHIVO BIGINT NOT NULL REFERENCES CON_ARCHIVO_CARGA(ID_ARCHIVO),
  NUMERO_LINEA BIGINT,
  TX_ORIGEN VARCHAR(500),
  TABLA_ORIGEN VARCHAR(500),
  TABLA_ORIGEN1 VARCHAR(500),
  EMPRESA VARCHAR(500),
  NUCTA VARCHAR(500),
  CEDESTIN VARCHAR(500),
  FECONT DATE,
  DEBE NUMERIC(24,4),
  HABER NUMERIC(24,4),
  SALDO_INICIAL NUMERIC(24,4),
  FECHA_CREACION TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS IX_CON_HA32_RESULTADO_ARCHIVO ON CON_HA32_RESULTADO(ID_ARCHIVO);
