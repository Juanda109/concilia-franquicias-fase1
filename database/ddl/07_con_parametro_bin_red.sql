CREATE TABLE IF NOT EXISTS CON_PARAMETRO_BIN_RED (
 ID_PARAMETRO BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, TIPO_CATALOGO VARCHAR(40) NOT NULL,
 BIN_DESDE VARCHAR(12) NOT NULL, BIN_HASTA VARCHAR(12) NOT NULL, RED VARCHAR(40), TIPO_TARJETA VARCHAR(40),
 FRANQUICIA VARCHAR(40), CLASIFICACION VARCHAR(80), VIGENTE_DESDE DATE, VIGENTE_HASTA DATE, ACTIVO BOOLEAN NOT NULL DEFAULT TRUE
);
