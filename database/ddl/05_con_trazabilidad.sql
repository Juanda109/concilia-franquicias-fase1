CREATE TABLE IF NOT EXISTS CON_TRAZABILIDAD (
 ID_TRAZA BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, ID_JORNADA BIGINT REFERENCES CON_JORNADA(ID_JORNADA),
 ID_ARCHIVO BIGINT REFERENCES CON_ARCHIVO_CARGA(ID_ARCHIVO), ETAPA VARCHAR(40) NOT NULL,
 ESTADO_ANTERIOR VARCHAR(40), ESTADO_NUEVO VARCHAR(40) NOT NULL, EVENTO VARCHAR(100) NOT NULL,
 DETALLE JSONB, CORRELATION_ID VARCHAR(120) NOT NULL,
 -- NULL en los eventos automaticos del parseo (ETAPA='PROCESAMIENTO'); se
 -- llenan solo en los eventos que origina una accion humana desde el backend
 -- (ETAPA='RECEPCION' - carga, rechazo, eliminacion).
 USUARIO_SUB VARCHAR(100), USUARIO_EMAIL VARCHAR(200),
 FECHA_EVENTO TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
