CREATE TABLE IF NOT EXISTS CON_CARTA_COMP_RESULTADO (
  ID_CARTA_COMP_RESULTADO BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ID_ARCHIVO BIGINT NOT NULL REFERENCES CON_ARCHIVO_CARGA(ID_ARCHIVO),
  NUMERO_LINEA BIGINT,
  CODIGO_MOVIMIENTO VARCHAR(500),
  CONCEPTO VARCHAR(500),
  NUMERO_NACIONAL BIGINT,
  NUMERO_INTERNAL BIGINT,
  NUMERO_TOTAL BIGINT,
  VALOR_NACIONAL NUMERIC(24,4),
  VALOR_INTERNAL NUMERIC(24,4),
  VALOR_TOTAL NUMERIC(24,4),
  VALOR_A_GIRAR NUMERIC(24,4),
  VALOR_INTERCAMBIO_PENDIENTE NUMERIC(24,4),
  COMISION_VISA_PENDIENTE NUMERIC(24,4),
  VALOR_TOTAL_PENDIENTE NUMERIC(24,4),
  BANCO_RECEPTOR VARCHAR(500),
  CODIGO_BANCO_RECEPTOR VARCHAR(500),
  FECHA_PROCESO DATE,
  ES_TOTAL_GENERAL BOOLEAN NOT NULL DEFAULT FALSE,
  FECHA_CREACION TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS IX_CON_CARTA_COMP_RESULTADO_ARCHIVO ON CON_CARTA_COMP_RESULTADO(ID_ARCHIVO);
