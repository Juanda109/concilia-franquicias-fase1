CREATE TABLE IF NOT EXISTS CON_CARTA_COMP_RESULTADO (
  ID_CARTA_COMP_RESULTADO BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ID_ARCHIVO BIGINT NOT NULL REFERENCES CON_ARCHIVO_CARGA(ID_ARCHIVO),
  NUMERO_LINEA BIGINT,
  SECCION VARCHAR(20) NOT NULL,
  MOTIVO_CODIGO VARCHAR(60) NOT NULL,
  ES_CONTROL BOOLEAN NOT NULL DEFAULT FALSE,
  LADO VARCHAR(10),
  CONCEPTO VARCHAR(200),
  VALOR_PRINCIPAL NUMERIC(24,4),
  VALOR_PROCESO NUMERIC(24,4),
  VALOR_FINANCIACION NUMERIC(24,4),
  VALOR_FOTOCOPIAS NUMERIC(24,4),
  VALOR_RED NUMERIC(24,4),
  VALOR_DEPOSITOS_ELECTRONICOS NUMERIC(24,4),
  VALOR_TOTAL NUMERIC(24,4),
  VALOR_OUTGOING NUMERIC(24,4),
  VALOR_INCOMING NUMERIC(24,4),
  FACTOR_COMPRA NUMERIC(18,4),
  FACTOR_VENTA NUMERIC(18,4),
  CINTA VARCHAR(20),
  FECHA_CINTA DATE,
  FECHA_CREACION TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS IX_CON_CARTA_COMP_RESULTADO_ARCHIVO ON CON_CARTA_COMP_RESULTADO(ID_ARCHIVO);
