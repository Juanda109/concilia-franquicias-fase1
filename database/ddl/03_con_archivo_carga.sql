CREATE TABLE IF NOT EXISTS CON_ARCHIVO_CARGA (
 ID_ARCHIVO BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ID_JORNADA BIGINT NOT NULL REFERENCES CON_JORNADA(ID_JORNADA),
 ID_INSUMO BIGINT NOT NULL REFERENCES CON_INSUMO_ESPERADO(ID_INSUMO),
 NOMBRE_ARCHIVO VARCHAR(500), FECHA_ARCHIVO DATE, TOTAL_REGISTROS BIGINT,
 REGISTROS_PROCESADOS BIGINT NOT NULL DEFAULT 0,
 ESTADO_RECEPCION VARCHAR(30) NOT NULL, ESTADO_PROCESAMIENTO VARCHAR(30) NOT NULL,
 NUMERO_INTENTO INTEGER NOT NULL DEFAULT 0, MAXIMO_INTENTOS INTEGER NOT NULL DEFAULT 3,
 NUMERO_REPROCESO INTEGER NOT NULL DEFAULT 0, MOTIVO_ESTADO TEXT, CORRELATION_ID VARCHAR(120) NOT NULL,
 FECHA_LIMITE_RECEPCION TIMESTAMPTZ, FECHA_CAMBIO_ESTADO TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FECHA_CREACION TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, UNIQUE(ID_JORNADA,ID_INSUMO)
);
