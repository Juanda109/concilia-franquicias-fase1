CREATE TABLE IF NOT EXISTS CON_VSS_REPORTE (
  ID_VSS_REPORTE BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ID_ARCHIVO BIGINT NOT NULL REFERENCES CON_ARCHIVO_CARGA(ID_ARCHIVO),
  NUMERO_LINEA BIGINT,
  REPORT_ID VARCHAR(500),
  REPORTING_FOR VARCHAR(500),
  ROLLUP_TO VARCHAR(500),
  FUNDS_XFER_ENTITY VARCHAR(500),
  PROC_DATE DATE,
  REPORT_DATE DATE,
  SETTLEMENT_CURRENCY CHAR(3),
  FECHA_CREACION TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS IX_CON_VSS_REPORTE_ARCHIVO ON CON_VSS_REPORTE(ID_ARCHIVO);
