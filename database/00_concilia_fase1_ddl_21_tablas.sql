-- 01 CON_JORNADA
CREATE TABLE IF NOT EXISTS CON_JORNADA (
 ID_JORNADA BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 FECHA_CONTABLE DATE NOT NULL UNIQUE, ESTADO VARCHAR(30) NOT NULL,
 ARCHIVOS_ESPERADOS SMALLINT NOT NULL DEFAULT 12 CHECK (ARCHIVOS_ESPERADOS=12),
 ARCHIVOS_RECIBIDOS SMALLINT NOT NULL DEFAULT 0, ARCHIVOS_PROCESADOS SMALLINT NOT NULL DEFAULT 0,
 ARCHIVOS_PENDIENTES SMALLINT NOT NULL DEFAULT 12, TOTAL_REGISTROS BIGINT NOT NULL DEFAULT 0,
 PORCENTAJE_AVANCE NUMERIC(5,2) NOT NULL DEFAULT 0,
 FECHA_INICIO TIMESTAMPTZ, FECHA_ULTIMA_ACTUALIZACION TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 02 CON_INSUMO_ESPERADO
CREATE TABLE IF NOT EXISTS CON_INSUMO_ESPERADO (
 ID_INSUMO BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, FUENTE VARCHAR(30) NOT NULL,
 TIPO_INSUMO VARCHAR(40) NOT NULL UNIQUE, PATRON_ARCHIVO VARCHAR(300), FORMATO VARCHAR(30) NOT NULL,
 OBLIGATORIO BOOLEAN NOT NULL DEFAULT TRUE, ORDEN_VISUAL SMALLINT NOT NULL UNIQUE,
 ESTADO_DESARROLLO VARCHAR(40) NOT NULL, VIGENTE_DESDE DATE, VIGENTE_HASTA DATE, ACTIVO BOOLEAN NOT NULL DEFAULT TRUE
);

-- 03 CON_ARCHIVO_CARGA
CREATE TABLE IF NOT EXISTS CON_ARCHIVO_CARGA (
 ID_ARCHIVO BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ID_JORNADA BIGINT NOT NULL REFERENCES CON_JORNADA(ID_JORNADA),
 ID_INSUMO BIGINT NOT NULL REFERENCES CON_INSUMO_ESPERADO(ID_INSUMO),
 NOMBRE_ARCHIVO VARCHAR(500), FECHA_ARCHIVO DATE, TOTAL_REGISTROS BIGINT,
 ESTADO_RECEPCION VARCHAR(30) NOT NULL, ESTADO_PROCESAMIENTO VARCHAR(30) NOT NULL,
 ESTADO_DISPONIBILIDAD VARCHAR(30) NOT NULL, DISPONIBLE BOOLEAN NOT NULL DEFAULT FALSE,
 NUMERO_INTENTO INTEGER NOT NULL DEFAULT 0, MAXIMO_INTENTOS INTEGER NOT NULL DEFAULT 3,
 NUMERO_REPROCESO INTEGER NOT NULL DEFAULT 0, MOTIVO_ESTADO TEXT, CORRELATION_ID VARCHAR(120) NOT NULL,
 FECHA_LIMITE_RECEPCION TIMESTAMPTZ, FECHA_CAMBIO_ESTADO TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FECHA_CREACION TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, UNIQUE(ID_JORNADA,ID_INSUMO)
);

-- 04 CON_CONTROL_ARCHIVO
CREATE TABLE IF NOT EXISTS CON_CONTROL_ARCHIVO (
 ID_CONTROL BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ID_ARCHIVO BIGINT NOT NULL REFERENCES CON_ARCHIVO_CARGA(ID_ARCHIVO), TIPO_CONTROL VARCHAR(80) NOT NULL,
 ESPERADO_REGISTROS BIGINT, OBTENIDO_REGISTROS BIGINT, ESPERADO_VALOR NUMERIC(24,4), OBTENIDO_VALOR NUMERIC(24,4),
 ESTADO VARCHAR(30) NOT NULL, DETALLE JSONB, FECHA_CONTROL TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 05 CON_TRAZABILIDAD
CREATE TABLE IF NOT EXISTS CON_TRAZABILIDAD (
 ID_TRAZA BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, ID_JORNADA BIGINT REFERENCES CON_JORNADA(ID_JORNADA),
 ID_ARCHIVO BIGINT REFERENCES CON_ARCHIVO_CARGA(ID_ARCHIVO), ETAPA VARCHAR(40) NOT NULL,
