-- V55: tabla de capturas manuales de la liquidacion VISA (Plantilla Maestra filas 161-181).
-- Aditiva: no modifica tablas existentes.
-- 25 CON_VISA_CAPTURA_MANUAL (celdas que la Plantilla Maestra digita a mano en la liquidacion VISA)
CREATE TABLE IF NOT EXISTS CON_VISA_CAPTURA_MANUAL (
 ID_CAPTURA BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ID_JORNADA BIGINT NOT NULL REFERENCES CON_JORNADA(ID_JORNADA),
 CAMPO VARCHAR(10) NOT NULL,
 VALOR NUMERIC(24,4),
 VERSION INTEGER NOT NULL,
 USUARIO VARCHAR(200) NOT NULL,
 OBSERVACION VARCHAR(500),
 FECHA_CREACION TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT UQ_CON_VISA_CAPTURA_VERSION UNIQUE (ID_JORNADA, CAMPO, VERSION),
 CONSTRAINT CK_CON_VISA_CAPTURA_CAMPO CHECK (CAMPO IN ('M169','L169','L170','L172','N179','N180','M177','L162')),
 CONSTRAINT CK_CON_VISA_CAPTURA_VERSION CHECK (VERSION > 0),
 CONSTRAINT CK_CON_VISA_CAPTURA_TRM CHECK (CAMPO <> 'M169' OR VALOR IS NULL OR VALOR > 0)
);
-- Historial: cada cambio inserta VERSION = MAX + 1 y se usa la ultima de cada
-- campo (VALOR NULL = campo borrado). Las celdas son las de la hoja
-- "PLANTILLA (2)": M169 TRM del correo, L169 total del correo, L170 pdf, L172 TII
-- GOF, N179/N180 controversias, M177 cuenta 196095001829, L162 carta.
