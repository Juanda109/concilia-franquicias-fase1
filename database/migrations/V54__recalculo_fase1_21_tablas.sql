CREATE TABLE IF NOT EXISTS CON_ERROR_REGISTRO (
 ID_ERROR BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ID_ARCHIVO BIGINT NOT NULL REFERENCES CON_ARCHIVO_CARGA(ID_ARCHIVO), NUMERO_LINEA BIGINT,
 TIPO_INSUMO VARCHAR(40) NOT NULL, ETAPA VARCHAR(40) NOT NULL, CAMPO VARCHAR(120), VALOR_ORIGEN TEXT,
 CODIGO_ERROR VARCHAR(80) NOT NULL, MENSAJE TEXT NOT NULL, DETALLE JSONB, CORRELATION_ID VARCHAR(120) NOT NULL,
 FECHA_ERROR TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS IX_CON_ERROR_REGISTRO_ARCHIVO_LINEA ON CON_ERROR_REGISTRO(ID_ARCHIVO,NUMERO_LINEA);

