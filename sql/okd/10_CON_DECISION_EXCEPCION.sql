CREATE TABLE CON_DECISION_EXCEPCION (
  ID_DECISION BIGSERIAL PRIMARY KEY,
  ID_EXCEPCION BIGINT NOT NULL REFERENCES CON_EXCEPCION(ID_EXCEPCION),
  ID_CRUCE BIGINT NOT NULL REFERENCES CON_CRUCE(ID_CRUCE),
  CAUSA_CONFIRMADA VARCHAR(100) NOT NULL,
  ACCION_TOMADA VARCHAR(100) NOT NULL,
  OBSERVACION VARCHAR(1000),
  USUARIO VARCHAR(100) NOT NULL,
  FEC_DECISION TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
