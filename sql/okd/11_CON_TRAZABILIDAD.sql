CREATE TABLE CON_TRAZABILIDAD (
  ID_TRAZABILIDAD BIGSERIAL PRIMARY KEY,
  CORRELATION_ID VARCHAR(64) NOT NULL,
  ID_ARCHIVO BIGINT REFERENCES CON_ARCHIVO_CARGA(ID_ARCHIVO),
  ID_CONCILIACION BIGINT REFERENCES CON_CONCILIACION(ID_CONCILIACION),
  ID_CRUCE BIGINT REFERENCES CON_CRUCE(ID_CRUCE),
  TIPO_EVENTO VARCHAR(50) NOT NULL,
  COMPONENTE VARCHAR(80) NOT NULL,
  DETALLE VARCHAR(2000),
  FEC_EVENTO TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- INDICES
CREATE INDEX IX_TRAZA_CORR ON CON_TRAZABILIDAD(CORRELATION_ID);
