CREATE TABLE CON_REPROCESO (
  ID_REPROCESO BIGSERIAL PRIMARY KEY,
  ID_CONCILIACION BIGINT REFERENCES CON_CONCILIACION(ID_CONCILIACION),
  ID_CRUCE BIGINT REFERENCES CON_CRUCE(ID_CRUCE),
  TIPO_REPROCESO VARCHAR(30) NOT NULL,
  MOTIVO VARCHAR(1000) NOT NULL,
  USUARIO VARCHAR(100) NOT NULL,
  VERSION_REGLAS INTEGER,
  ESTADO VARCHAR(30) DEFAULT 'SOLICITADO',
  FEC_SOLICITUD TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FEC_EJECUCION TIMESTAMP
);
