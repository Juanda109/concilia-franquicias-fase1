-- RECON_F2_017
-- Migracion pendiente de ejecucion.
-- Historial inmutable de confirmaciones TRM Visa.
-- La fecha de referencia proviene de CON_JORNADA.

BEGIN;

-- RECON_F2_017_SQL_INTEGRIDAD
DO $$
BEGIN
    IF current_database() <> 'concilia_test' THEN
        RAISE EXCEPTION 'Base de datos no autorizada';
    END IF;

    IF to_regclass('public.con_trm_jornada') IS NOT NULL THEN
        RAISE EXCEPTION 'Tabla TRM existente; revisar migracion';
    END IF;
END;
$$;


CREATE TABLE public.con_trm_jornada (
    id_trm BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_jornada BIGINT NOT NULL
        REFERENCES public.con_jornada(id_jornada),
    fecha_referencia DATE NOT NULL,
    version INTEGER NOT NULL,
    trm_oficial NUMERIC(18,4),
    trm_aplicada NUMERIC(18,4) NOT NULL,
    fuente VARCHAR(200) NOT NULL,
    referencia_fuente TEXT,
    modificada_manualmente BOOLEAN NOT NULL,
    justificacion TEXT,
    usuario_confirmacion VARCHAR(120) NOT NULL,
    fecha_confirmacion TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT uq_trm_jornada_version
        UNIQUE (id_jornada, version),

    CONSTRAINT ck_trm_version
        CHECK (version > 0),

    CONSTRAINT ck_trm_aplicada
        CHECK (trm_aplicada > 0),

    CONSTRAINT ck_trm_oficial
        CHECK (trm_oficial IS NULL OR trm_oficial > 0),

    CONSTRAINT ck_trm_fuente
        CHECK (length(btrim(fuente)) > 0),

    CONSTRAINT ck_trm_usuario
        CHECK (length(btrim(usuario_confirmacion)) > 0),

    CONSTRAINT ck_trm_manual
        CHECK (
            (
                modificada_manualmente
                AND length(btrim(coalesce(justificacion,''))) > 0
            )
            OR
            (
                NOT modificada_manualmente
                AND trm_oficial IS NOT NULL
                AND trm_aplicada = trm_oficial
            )
        )
);

CREATE INDEX ix_trm_jornada_fecha
ON public.con_trm_jornada(id_jornada, fecha_referencia);

-- No se crea trigger de auditoria ni se modifica CON_JORNADA.
-- El repositorio futuro debera:
-- 1. Bloquear la jornada mediante SELECT FOR UPDATE.
-- 2. Tomar fecha_referencia de CON_JORNADA.
-- 3. Calcular version = MAX(version) + 1 bajo ese bloqueo.
-- 4. Insertar una confirmacion nueva sin sobrescribir anteriores.
-- 5. Obtener usuario_confirmacion del contexto autenticado.
-- 6. Verificar que la jornada permite modificaciones.
-- 7. Invalidar los calculos derivados anteriores.
-- 8. Prohibir UPDATE/DELETE mediante permisos y controles
--    adicionales antes de habilitar la API de escritura.


-- Validar jornada y fecha en cada insercion.
CREATE FUNCTION public.fn_validar_trm_jornada_040()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_fecha DATE;
    v_estado VARCHAR;
BEGIN
    SELECT fecha_contable, estado
      INTO v_fecha, v_estado
      FROM public.con_jornada
     WHERE id_jornada = NEW.id_jornada
     FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Jornada TRM inexistente';
    END IF;

    IF v_estado <> 'PENDIENTE' THEN
        RAISE EXCEPTION 'Estado de jornada no autorizado';
    END IF;

    IF NEW.fecha_referencia <> v_fecha THEN
        RAISE EXCEPTION
            'Fecha TRM diferente de fecha contable';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_validar_trm_jornada_040
BEFORE INSERT ON public.con_trm_jornada
FOR EACH ROW
EXECUTE FUNCTION public.fn_validar_trm_jornada_040();


-- Proteger historial de confirmaciones.
CREATE FUNCTION public.fn_trm_historial_inmutable_040()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION
        'Historial TRM inmutable: operacion no permitida';
END;
$$;

CREATE TRIGGER trg_trm_historial_inmutable_040
BEFORE UPDATE OR DELETE ON public.con_trm_jornada
FOR EACH ROW
EXECUTE FUNCTION public.fn_trm_historial_inmutable_040();


COMMIT;
