CREATE TABLE IF NOT EXISTS public.con_canje_detalle (
    id_canje_detalle BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_archivo BIGINT NOT NULL REFERENCES public.con_archivo_carga(id_archivo),
    tipo_archivo VARCHAR(4) NOT NULL CHECK (tipo_archivo IN ('CAET','CANT')),
    fecha_contable DATE NOT NULL,
    linea_origen BIGINT NOT NULL CHECK (linea_origen > 0),
    correlation_id VARCHAR(64) NOT NULL,
    tx TEXT,
    bin_dest TEXT,
    tipo TEXT,
    fecha_canje TEXT,
    ofi TEXT,
    tarjeta TEXT,
    vl_total NUMERIC(24,4),
    vl_descue NUMERIC(24,4),
    vl_interc NUMERIC(24,4),
    plaz TEXT,
    mot_cob TEXT,
    iden_red TEXT,
    cod_error TEXT,
    mo_to TEXT,
    ind_cash TEXT,
    espacios TEXT,
    comision_op_exitosas NUMERIC(24,4),
    cuenta TEXT,
    cuentas_comisiones TEXT,
    tii_recibida_emisor_visa_op_rever_ventas NUMERIC(24,4),
    xx TEXT,
    cuenta_880 TEXT,
    CONSTRAINT uq_canje_archivo_linea UNIQUE (id_archivo, linea_origen)
);
CREATE INDEX IF NOT EXISTS ix_canje_tipo_fecha ON public.con_canje_detalle(tipo_archivo,fecha_contable);

