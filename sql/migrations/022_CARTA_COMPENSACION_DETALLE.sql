BEGIN;
SET LOCAL lock_timeout = '5s';
DO $$ BEGIN
 IF current_database() <> 'concilia_test' THEN
  RAISE EXCEPTION 'Base no autorizada';
 END IF;
END $$;
CREATE TABLE public.con_carta_compensacion_detalle (
 id_carta_detalle BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_archivo BIGINT NOT NULL REFERENCES public.con_archivo_carga(id_archivo),
 fecha_contable DATE NOT NULL,
 linea_origen BIGINT NOT NULL,
 correlation_id VARCHAR(64) NOT NULL,
 seccion TEXT,
 motivo_codigo TEXT,
 es_control BOOLEAN,
 lado TEXT,
 concepto TEXT,
 valor_principal NUMERIC(24,4),
 valor_proceso NUMERIC(24,4),
 valor_financiacion NUMERIC(24,4),
 valor_fotocopias NUMERIC(24,4),
 valor_red NUMERIC(24,4),
 valor_depositos_electronicos NUMERIC(24,4),
 valor_total NUMERIC(24,4),
 valor_outgoing NUMERIC(24,4),
 valor_incoming NUMERIC(24,4),
 factor_compra NUMERIC(24,8),
 factor_venta NUMERIC(24,8),
 cinta TEXT,
 fecha_cinta TEXT,
 CONSTRAINT uq_carta_archivo_seccion_linea UNIQUE(id_archivo,seccion,linea_origen)
);
CREATE INDEX ix_carta_detalle_archivo ON public.con_carta_compensacion_detalle(id_archivo);
COMMIT;
