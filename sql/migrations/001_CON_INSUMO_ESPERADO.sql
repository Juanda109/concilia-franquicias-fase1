CREATE TABLE CON_INSUMO_ESPERADO (
    ID_INSUMO_ESPERADO BIGSERIAL PRIMARY KEY,
    ID_JORNADA BIGINT NOT NULL
        REFERENCES CON_JORNADA(ID_JORNADA),

    TIPO_INSUMO VARCHAR(40) NOT NULL,
    FUENTE VARCHAR(30) NOT NULL,

    OBLIGATORIO BOOLEAN NOT NULL DEFAULT TRUE,
    ESTADO VARCHAR(30) NOT NULL DEFAULT 'PENDIENTE',

    ID_ARCHIVO BIGINT
        REFERENCES CON_ARCHIVO_CARGA(ID_ARCHIVO),

    FEC_RECEPCION TIMESTAMP,
    FEC_ACTUALIZACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT UQ_INSUMO_JORNADA
        UNIQUE (ID_JORNADA, TIPO_INSUMO),

    CONSTRAINT CK_TIPO_INSUMO_F1
        CHECK (
            TIPO_INSUMO IN (
                'HA22',
                'HA26',
                'HA32',
                'CAET',
                'CANT',
                'DEPO',
                'CARTA_COMPENSACION',
                'PMD',
                'MEP',
                'VSS'
            )
        )
);

CREATE INDEX IX_INSUMO_JORNADA_ESTADO
ON CON_INSUMO_ESPERADO(ID_JORNADA, ESTADO);
