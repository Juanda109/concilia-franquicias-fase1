-- CONCILIA V1 - FASE 2
-- Migracion 039: versionamiento auditable de archivos por insumo/jornada.
-- Conserva archivos y detalles anteriores. No elimina ni reescribe evidencia.

BEGIN;
SET LOCAL lock_timeout = '5s';

DO $$
BEGIN
    IF to_regclass('public.con_insumo_esperado') IS NULL
       OR to_regclass('public.con_archivo_carga') IS NULL THEN
        RAISE EXCEPTION 'Faltan tablas base para versionamiento de insumos';
    END IF;

    IF to_regclass('public.con_insumo_archivo_version') IS NOT NULL THEN
        RAISE EXCEPTION 'con_insumo_archivo_version ya existe; revisar antes de continuar';
    END IF;

    IF EXISTS (
        SELECT 1
        FROM public.con_insumo_esperado
        WHERE id_archivo IS NOT NULL
        GROUP BY id_archivo
        HAVING COUNT(*) > 1
    ) THEN
        RAISE EXCEPTION
            'Un mismo id_archivo esta asociado a varios insumos; regularizar antes del backfill';
    END IF;
END
$$;

CREATE TABLE public.con_insumo_archivo_version (
    id_version_insumo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_insumo_esperado BIGINT NOT NULL
        REFERENCES public.con_insumo_esperado(id_insumo_esperado),
    numero_version INTEGER NOT NULL CHECK (numero_version > 0),
    id_archivo BIGINT NOT NULL UNIQUE
        REFERENCES public.con_archivo_carga(id_archivo),
    id_archivo_anterior BIGINT
        REFERENCES public.con_archivo_carga(id_archivo),
    estado_version VARCHAR(20) NOT NULL DEFAULT 'VIGENTE'
        CHECK (estado_version IN ('VIGENTE', 'SUSTITUIDA')),
    motivo_version VARCHAR(500),
    fec_registro TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_insumo_numero_version
        UNIQUE (id_insumo_esperado, numero_version),
    CONSTRAINT ck_primera_version_sin_anterior
        CHECK (numero_version <> 1 OR id_archivo_anterior IS NULL),
    CONSTRAINT ck_version_sucesiva_con_anterior
        CHECK (numero_version = 1 OR id_archivo_anterior IS NOT NULL)
);

CREATE UNIQUE INDEX uq_insumo_version_vigente
    ON public.con_insumo_archivo_version(id_insumo_esperado)
    WHERE estado_version = 'VIGENTE';

CREATE INDEX ix_insumo_version_archivo
    ON public.con_insumo_archivo_version(id_archivo);

-- Backfill: el archivo actualmente asociado queda como version 1.
-- El historial anterior a esta migracion no se inventa; se registra como
-- primera version conocida y se conserva su id_archivo original.
INSERT INTO public.con_insumo_archivo_version (
    id_insumo_esperado,
    numero_version,
    id_archivo,
    id_archivo_anterior,
    estado_version,
    motivo_version
)
SELECT
    i.id_insumo_esperado,
    1,
    i.id_archivo,
    NULL,
    'VIGENTE',
    'Version inicial conocida al instalar migracion 039'
FROM public.con_insumo_esperado i
WHERE i.id_archivo IS NOT NULL;

COMMENT ON TABLE public.con_insumo_archivo_version IS
'Historial inmutable de versiones recibidas para cada insumo de una jornada. El archivo previo y sus detalles se conservan.';

COMMIT;
