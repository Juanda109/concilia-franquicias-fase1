-- CONCILIA V1 - FASE 2
-- Migracion 038: persistencia documental Carta Auxiliar V69.
-- No habilita homologacion monetaria.
-- No modifica las tablas financieras existentes.

BEGIN;

SET LOCAL lock_timeout = '5s';

DO $$
BEGIN
    IF current_database() <> 'concilia_test' THEN
        RAISE EXCEPTION 'Base de datos no autorizada';
    END IF;

    IF to_regclass('public.con_carta_auxiliar_pagina') IS NOT NULL
       OR to_regclass('public.con_carta_auxiliar_linea') IS NOT NULL
       OR to_regclass('public.con_carta_auxiliar_alerta') IS NOT NULL
    THEN
        RAISE EXCEPTION
            'Ya existen tablas auxiliares V69. Revisar antes de instalar.';
    END IF;
END
$$;

-- 1. Evidencia documental por pagina.

CREATE TABLE public.con_carta_auxiliar_pagina (
    id_auxiliar_pagina BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_archivo BIGINT NOT NULL
        REFERENCES public.con_archivo_carga(id_archivo),
    id_jornada BIGINT NOT NULL
        REFERENCES public.con_jornada(id_jornada),

    correlation_id VARCHAR(64) NOT NULL,
    checksum_archivo VARCHAR(64) NOT NULL
        CHECK (LENGTH(checksum_archivo) = 64),

    nombre_hoja VARCHAR(120) NOT NULL,
    familia VARCHAR(80) NOT NULL,
    referencia_meet VARCHAR(80),
    codigo_cabecera VARCHAR(80),
    estado_identidad VARCHAR(100) NOT NULL,

    pagina_logica INTEGER NOT NULL CHECK (pagina_logica > 0),
    pagina_impresa VARCHAR(30),

    linea_inicio BIGINT NOT NULL CHECK (linea_inicio > 0),
    linea_fin BIGINT NOT NULL CHECK (linea_fin >= linea_inicio),

    filas_con_texto INTEGER NOT NULL DEFAULT 0,
    filas_candidatas INTEGER NOT NULL DEFAULT 0,

    fecha_impresion DATE,
    fecha_proceso DATE,
    fecha_canje DATE,
    fecha_sistema DATE,
    fecha_reporte DATE,
    fecha_outclear DATE,

    fecha_contable_objetivo DATE NOT NULL,
    estado_fecha VARCHAR(32) NOT NULL,
    codigo_vss VARCHAR(40),

    tipos_de_linea JSONB NOT NULL DEFAULT '{}'::jsonb,
    huella_sha256 VARCHAR(64) NOT NULL
        CHECK (LENGTH(huella_sha256) = 64),

    habilitado_f2_monetario BOOLEAN NOT NULL DEFAULT FALSE
        CHECK (habilitado_f2_monetario = FALSE),

    fec_persistencia TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_carta_aux_pagina
        UNIQUE (id_archivo, nombre_hoja, pagina_logica)
);

CREATE INDEX ix_carta_aux_pagina_jornada
    ON public.con_carta_auxiliar_pagina(id_jornada, familia);

CREATE INDEX ix_carta_aux_pagina_archivo
    ON public.con_carta_auxiliar_pagina(id_archivo);


-- 2. Evidencia por linea documental.

CREATE TABLE public.con_carta_auxiliar_linea (
    id_auxiliar_linea BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    id_auxiliar_pagina BIGINT NOT NULL
        REFERENCES public.con_carta_auxiliar_pagina(id_auxiliar_pagina)
        ON DELETE CASCADE,

    id_archivo BIGINT NOT NULL
        REFERENCES public.con_archivo_carga(id_archivo),

    id_jornada BIGINT NOT NULL
        REFERENCES public.con_jornada(id_jornada),

    correlation_id VARCHAR(64) NOT NULL,
    checksum_archivo VARCHAR(64) NOT NULL
        CHECK (LENGTH(checksum_archivo) = 64),

    nombre_hoja VARCHAR(120) NOT NULL,
    familia VARCHAR(80) NOT NULL,
    pagina_logica INTEGER NOT NULL,
    numero_linea BIGINT NOT NULL CHECK (numero_linea > 0),

    tipo_linea VARCHAR(100) NOT NULL,
    codigo_transaccion_literal VARCHAR(120),
    codigo_vss VARCHAR(40),

    huella_sha256 VARCHAR(64) NOT NULL
        CHECK (LENGTH(huella_sha256) = 64),

    habilitado_f2_monetario BOOLEAN NOT NULL DEFAULT FALSE
        CHECK (habilitado_f2_monetario = FALSE),

    fec_persistencia TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_carta_aux_linea
        UNIQUE (id_auxiliar_pagina, numero_linea)
);

CREATE INDEX ix_carta_aux_linea_archivo
    ON public.con_carta_auxiliar_linea(id_archivo);

CREATE INDEX ix_carta_aux_linea_codigo
    ON public.con_carta_auxiliar_linea(codigo_transaccion_literal);


-- 3. Alertas y observaciones documentales.

CREATE TABLE public.con_carta_auxiliar_alerta (
    id_auxiliar_alerta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    id_archivo BIGINT NOT NULL
        REFERENCES public.con_archivo_carga(id_archivo),

    id_jornada BIGINT NOT NULL
        REFERENCES public.con_jornada(id_jornada),

    id_auxiliar_pagina BIGINT
        REFERENCES public.con_carta_auxiliar_pagina(id_auxiliar_pagina)
        ON DELETE CASCADE,

    correlation_id VARCHAR(64) NOT NULL,
    checksum_archivo VARCHAR(64) NOT NULL
        CHECK (LENGTH(checksum_archivo) = 64),

    tipo_alerta VARCHAR(100) NOT NULL,
    nombre_hoja VARCHAR(120),
    pagina_logica INTEGER,

    detalle JSONB NOT NULL DEFAULT '{}'::jsonb,

    huella_sha256 VARCHAR(64) NOT NULL
        CHECK (LENGTH(huella_sha256) = 64),

    fec_persistencia TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_carta_aux_alerta
        UNIQUE (id_archivo, huella_sha256)
);

CREATE INDEX ix_carta_aux_alerta_jornada
    ON public.con_carta_auxiliar_alerta(id_jornada, tipo_alerta);


COMMENT ON TABLE public.con_carta_auxiliar_pagina IS
'Evidencia documental de paginas auxiliares Carta V69.';

COMMENT ON TABLE public.con_carta_auxiliar_linea IS
'Evidencia documental por linea. No representa movimientos homologados.';

COMMENT ON TABLE public.con_carta_auxiliar_alerta IS
'Alertas documentales y temporales de Carta V69.';

COMMIT;