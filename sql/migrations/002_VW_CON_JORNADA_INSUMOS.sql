CREATE OR REPLACE VIEW VW_CON_JORNADA_INSUMOS AS
SELECT
    J.ID_JORNADA,
    J.FECHA_CONTABLE,
    J.ESTADO AS ESTADO_JORNADA,
    COUNT(I.ID_INSUMO_ESPERADO) AS TOTAL_INSUMOS,
    COUNT(I.ID_INSUMO_ESPERADO)
        FILTER (WHERE I.OBLIGATORIO = TRUE) AS TOTAL_OBLIGATORIOS,
    COUNT(I.ID_INSUMO_ESPERADO)
        FILTER (WHERE I.ESTADO = 'PENDIENTE') AS TOTAL_PENDIENTES,
    COUNT(I.ID_INSUMO_ESPERADO)
        FILTER (WHERE I.ESTADO = 'RECIBIDO') AS TOTAL_RECIBIDOS,
    COUNT(I.ID_INSUMO_ESPERADO)
        FILTER (WHERE I.ESTADO = 'VALIDADO') AS TOTAL_VALIDADOS,
    COUNT(I.ID_INSUMO_ESPERADO)
        FILTER (WHERE I.ESTADO = 'RECHAZADO') AS TOTAL_RECHAZADOS
FROM CON_JORNADA J
LEFT JOIN CON_INSUMO_ESPERADO I
    ON I.ID_JORNADA = J.ID_JORNADA
GROUP BY
    J.ID_JORNADA,
    J.FECHA_CONTABLE,
    J.ESTADO;
