CREATE TABLE CON_PARAMETRO_BIN_RED (
    ID_PARAMETRO_BIN BIGSERIAL PRIMARY KEY,

    TIPO_CATALOGO VARCHAR(40) NOT NULL,
    BIN_DESDE VARCHAR(6) NOT NULL,
    TIPO_TARJETA VARCHAR(40) NOT NULL,

    VERSION_CATALOGO INTEGER NOT NULL DEFAULT 1,
    ACTIVO BOOLEAN NOT NULL DEFAULT TRUE,

    FEC_DESDE DATE NOT NULL DEFAULT CURRENT_DATE,
    FEC_HASTA DATE,

    FEC_CREACION TIMESTAMP NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT CK_BIN_SEIS_DIGITOS
        CHECK (BIN_DESDE ~ '^[0-9]{6}$'),

    CONSTRAINT CK_VERSION_BIN_POSITIVA
        CHECK (VERSION_CATALOGO > 0),

    CONSTRAINT CK_VIGENCIA_BIN
        CHECK (
            FEC_HASTA IS NULL
            OR FEC_HASTA >= FEC_DESDE
        ),

    CONSTRAINT UQ_BIN_CATALOGO_VERSION
        UNIQUE (
            TIPO_CATALOGO,
            BIN_DESDE,
            VERSION_CATALOGO
        )
);

CREATE INDEX IX_BIN_RED_BUSQUEDA
ON CON_PARAMETRO_BIN_RED (
    TIPO_CATALOGO,
    BIN_DESDE
)
WHERE ACTIVO = TRUE;

-- Evita multiples clasificaciones activas para un mismo BIN.
CREATE UNIQUE INDEX UQ_BIN_RED_ACTIVO
ON CON_PARAMETRO_BIN_RED (
    TIPO_CATALOGO,
    BIN_DESDE
)
WHERE ACTIVO = TRUE;
